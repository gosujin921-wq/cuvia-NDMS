/* ─────────────────────────────────────────────
 * 노출 시간 — 위험이 시작된 뒤 조치가 끝나기까지 걸린 시간 (README §2.3 기준 ③ · 03 §26.6)
 *
 * 노출 대응(통제·대피·순회)은 재난 현상을 바꾸지 않는다. 결과로 쓰는 것은 **시간**이다 —
 * 조치가 도달보다 얼마나 앞섰나, 중단이 몇 분이었나. 시각 둘을 빼서 나오는 값이라 모델이 필요 없다.
 *
 * ★ 수는 세지 않는다(2026-09-16). "시간당 유입 × 시간"으로 차량·인원·가구 수를 만들던 규칙은 걷었다 —
 *   일찍 할수록 그만큼 준다는 산수라 트윈이 계산한 결과가 아니다. 대상은 이름과 상태(노출 · 통제됨)로만 선다.
 * ───────────────────────────────────────────── */

const ms = (iso: string) => new Date(iso).getTime();

/** 위험 시작부터 조치 완료까지 걸린 분 — "요양시설 연기 노출 50분" 같은 시간형 노출 */
export function exposedMinutes(onset: string | null, until: string): number {
  if (!onset) return 0;
  return Math.max(0, Math.round((ms(until) - ms(onset)) / 60_000));
}
